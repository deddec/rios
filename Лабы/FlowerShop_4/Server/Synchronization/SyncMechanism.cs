namespace FlowerShop.Server;

/// <summary>
/// Механизм синхронизации доступа к общему ресурсу (ЛР №3, часть 1).
/// Выбор механизма — параметр сервера: <c>dotnet run --project Server -- --sync=lock</c>.
/// </summary>
public enum SyncMechanism
{
    /// <summary>
    /// Без синхронизации — поведение ЛР №2: проверка и изменение ресурса не атомарны,
    /// возникает Race Condition. Оставлен для сравнения «до/после» (Таблица 1).
    /// </summary>
    None,

    /// <summary>
    /// lock (Monitor) — основной механизм ЛР №3 (Требование 5).
    /// Синхронный примитив: на время выполнения критической секции удерживается поток.
    /// </summary>
    Lock,

    /// <summary>
    /// SemaphoreSlim на одно разрешение — альтернативный механизм (Требование 9).
    /// Асинхронный примитив: WaitAsync не блокирует поток, внутри критической
    /// секции допустимы await.
    /// </summary>
    SemaphoreSlim
}
